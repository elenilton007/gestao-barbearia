RAIZ = os.path.join(os.path.dirname(__file__), "..")


def _apagar_tabelas():
    conn = database.get_connection()
    for tabela in ("tentativas_login", "usuarios", "atendimentos", "clientes",
                   "servicos", "barbeiros", "barbearias"):
        conn.execute(f"DROP TABLE IF EXISTS {tabela}")
    conn.commit()
    conn.close()


# ---------- TRADUÇÃO PARA O POSTGRESQL ----------

def test_para_postgres_traduz_o_schema():
    sql = database.para_postgres(
        "CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, preco REAL NOT NULL, "
        "criado_em TEXT DEFAULT (datetime('now')))"
    )
    assert "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in sql
    assert "preco DOUBLE PRECISION NOT NULL" in sql
    assert "now() AT TIME ZONE 'UTC'" in sql
    assert "AUTOINCREMENT" not in sql and "datetime" not in sql


def test_para_postgres_troca_os_parametros():
    sql = database.para_postgres(
        "SELECT * FROM t WHERE nome LIKE '50%' AND id = ? AND x = ?", com_parametros=True
    )
    assert sql == "SELECT * FROM t WHERE nome LIKE '50%%' AND id = %s AND x = %s"


def test_para_postgres_sem_parametros_nao_mexe_no_porcento():
    assert database.para_postgres("SELECT '50%'") == "SELECT '50%'"


def test_linha_funciona_como_a_do_sqlite():
    linha = database.Linha(("id", "nome"), (7, "Carlos"))
    assert linha["nome"] == "Carlos"
    assert linha[0] == 7
    assert linha.keys() == ["id", "nome"]
    assert list(linha) == [7, "Carlos"]
    assert len(linha) == 2
    with pytest.raises(IndexError):
        linha["telefone"]


