def _config_do_app(**ambiente):
    resultado = subprocess.run(
        [sys.executable, "-c",
         "import app; print(app.app.config['SESSION_COOKIE_SECURE'])"],
        cwd=RAIZ,
        env={**os.environ, "SECRET_KEY": "x", **ambiente},
        capture_output=True,
        text=True,
        check=True,
    )
    return resultado.stdout.strip()


def test_cookie_seguro_so_com_cookie_seguro_1():
    assert _config_do_app() == "False"
    assert _config_do_app(COOKIE_SEGURO="1") == "True"


def _porta_livre():
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def test_app_roda_no_gunicorn(tmp_path):
    """Sobe o Gunicorn como no Dockerfile e abre a tela de login."""
    porta = _porta_livre()
    ambiente = {**os.environ, "SECRET_KEY": "chave-de-teste",
                "BARBEARIA_DB": str(tmp_path / "gunicorn.db")}
    ambiente.pop("FLASK_DEBUG", None)
    subprocess.run([sys.executable, "database.py", "--preparar"],
                   cwd=RAIZ, env=ambiente, check=True, capture_output=True)
    servidor = subprocess.Popen(
        [sys.executable, "-m", "gunicorn", "app:app", "--bind", f"127.0.0.1:{porta}",
         "--workers", "2"],
        cwd=RAIZ, env=ambiente, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
    )
    sem_proxy = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    try:
        limite = time.time() + 30
        while True:
            try:
                with sem_proxy.open(f"http://127.0.0.1:{porta}/login") as resposta:
                    assert resposta.status == 200
                    assert "csrf_token" in resposta.read().decode()
                break
            except OSError:
                if time.time() > limite or servidor.poll() is not None:
                    raise
                time.sleep(0.2)
    finally:
        servidor.terminate()
        servidor.wait(timeout=10)


