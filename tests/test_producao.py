"""
test_producao.py

Preparação para produção: tradução do SQL para o PostgreSQL, linhas do
PostgreSQL que funcionam como as do SQLite, criação das tabelas num banco
vazio sem apagar nada, proteção contra apagar o banco de produção,
cookie seguro e o app rodando de verdade no Gunicorn.

Estes testes rodam no banco escolhido pelo conftest (SQLite, ou o
PostgreSQL de TEST_DATABASE_URL).
"""

